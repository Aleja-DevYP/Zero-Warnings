def validar_movimientos_caballo(pos_inicial: str, n: int, cadena_movimientos: str) -> str:
    tokens = cadena_movimientos.strip().split()
    pos_actual = pos_inicial.lower()
    
    for i, token in enumerate(tokens, start=1):
        if len(token) != 3 or token[0].upper() != 'K':
            return f"INCORRECTO falla letra {token[0]} no pertenece a un caballo." if len(token) > 0 else f"INCORRECTO falla en el movimiento {i}"
        
        col_dest = token[1].lower()
        fila_dest = token[2]
        
        if col_dest not in 'abcdefgh' or fila_dest not in '12345678':
            return f"INCORRECTO falla en el movimiento {i}"
        
        d_col = abs(ord(col_dest) - ord(pos_actual[0]))
        d_fila = abs(int(fila_dest) - int(pos_actual[1]))
        
        if not ((d_col == 1 and d_fila == 2) or (d_col == 2 and d_fila == 1)):
            return f"INCORRECTO falla en el movimiento {i}"
        
        pos_actual = col_dest + fila_dest

    return "movimiento CORRECTO."

